"""Coefficient and constant generator for the M3 transcendentals.

Chebyshev near-minimax fits via mpmath.chebyfit, freshly computed (no
third-party tables), rounded to the 5-byte format by the oracle encoder.
Emits src/lnexpconst.asm and an importable table. Also reports each fit's
theoretical error so the spec's accuracy claims are grounded.

ln kernel:  ln(s) = 2z * P(z^2),  z = (s-1)/(s+1),  s in [1/sqrt2, sqrt2)
            -> fit P(w) on w in [0, z_max^2], z_max = (sqrt2-1)/(sqrt2+1)
exp kernel: exp(r) = Q(r), r in [-ln2/2, ln2/2]
Constants:  ln2 (5-byte), Cody-Waite split L1 (top 16 mantissa bits) and
            L2 = ln2 - L1 exactly representable, 1/ln2, sqrt2/2 boundary.
"""
import sys
sys.path.insert(0, __file__.rsplit("/", 1)[0])
from fractions import Fraction
import mpmath as mp
from oracle import encode, FP5

mp.mp.prec = 120


def to_fp5(x) -> FP5:
    fr = Fraction(mp.nstr(x, 40, strip_zeros=False)) if not isinstance(x, Fraction) else x
    return encode(fr, prefer_int=False)


def frac_of(x) -> Fraction:
    # exact binary fraction of an mpf
    m, e = mp.mpf(x).man_exp if hasattr(mp.mpf(x), "man_exp") else (None, None)
    if m is None:
        t = mp.mpf(x)
        m, e = t._mpf_[1], t._mpf_[2]
        if t < 0:
            m = -m
    return Fraction(int(m), 1) * Fraction(2) ** int(e)


def fit(f, a, b, deg):
    poly, err = mp.chebyfit(f, [a, b], deg, error=True)
    return [frac_of(c) for c in poly], float(err)


def main():
    z_max = (mp.sqrt(2) - 1) / (mp.sqrt(2) + 1)
    w_max = z_max ** 2

    # P(w): ln(s) = 2 z P(z^2); P(w) = atanh(sqrt(w))/sqrt(w) = sum w^k/(2k+1)
    def P(w):
        if w == 0:
            return mp.mpf(1)
        z = mp.sqrt(w)
        return mp.atanh(z) / z

    pcoef, perr = fit(P, 0, float(w_max), 5)          # degree 4 in w
    qcoef, qerr = fit(mp.exp, -float(mp.log(2)) / 2, float(mp.log(2)) / 2, 9)

    ln2 = frac_of(mp.log(2))
    # Cody-Waite: L1 = ln2 with mantissa truncated to 16 bits (exact in fmt)
    l1 = Fraction(int(ln2 * 2**16) if False else (ln2.numerator * 2**16) // ln2.denominator, 2**16)
    # cleaner: L1 = floor(ln2 * 2^16) / 2^16
    from math import floor
    l1 = Fraction(floor(ln2 * 2**16), 2**16)
    l2 = ln2 - l1
    inv_ln2 = frac_of(1 / mp.log(2))
    sqrt2o2 = frac_of(mp.sqrt(2) / 2)

    named = [("CONE", encode(Fraction(1), prefer_int=False)),
             ("CLN2", encode(ln2, prefer_int=False)),
             ("CL1", encode(l1, prefer_int=False)),
             ("CL2", encode(l2, prefer_int=False)),
             ("CINVLN2", encode(inv_ln2, prefer_int=False)),
             ("CSQRT2O2", encode(sqrt2o2, prefer_int=False))]
    # polynomial tables, highest-degree coefficient first (Horner order)
    ptab = [encode(c, prefer_int=False) for c in pcoef]
    qtab = [encode(c, prefer_int=False) for c in qcoef]

    lines = ["; GENERATED by tools/gencoeff.py -- do not edit by hand",
             "; SPDX-License-Identifier: Apache-2.0 OR GPL-2.0-only OR GPL-3.0-only OR MPL-2.0",
             f"; ln kernel Chebyshev fit error:  {perr:.3e}",
             f"; exp kernel Chebyshev fit error: {qerr:.3e}"]
    for name, v in named:
        lines.append(f"{name}:  DEFB {', '.join('0x%02X' % x for x in v.b)}")
    lines.append(f"LNPOLY_N: DEFB {len(ptab)}")
    lines.append("LNPOLY:")
    for i, v in enumerate(ptab):
        lines.append(f"        DEFB {', '.join('0x%02X' % x for x in v.b)} ; w^{len(ptab)-1-i}")
    lines.append(f"EXPPOLY_N: DEFB {len(qtab)}")
    lines.append("EXPPOLY:")
    for i, v in enumerate(qtab):
        lines.append(f"        DEFB {', '.join('0x%02X' % x for x in v.b)} ; r^{len(qtab)-1-i}")
    open("src/lnexpconst.asm", "w").write("\n".join(lines) + "\n")
    print("\n".join(lines[:6]))
    print(f"P coefficients: {len(ptab)}, Q coefficients: {len(qtab)}")
    return {"P": ptab, "Q": qtab, "named": dict(named)}


def table():
    return main.__wrapped__() if hasattr(main, "__wrapped__") else _cached()


_cache = None
def _cached():
    global _cache
    if _cache is None:
        import io, contextlib
        with contextlib.redirect_stdout(io.StringIO()):
            _cache = main()
    return _cache


if __name__ == "__main__":
    main()
