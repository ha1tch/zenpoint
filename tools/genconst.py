"""Emit the shared constant table (spec strings.md sec.3) as assembly and
as an importable Python dict. Constants come from the oracle encoder only."""
import sys
sys.path.insert(0, __file__.rsplit("/", 1)[0])
from fractions import Fraction
from oracle import encode

CONSTS = [("P10_0", 10**1), ("P10_1", 10**2), ("P10_2", 10**4),
          ("P10_3", 10**8), ("P10_4", 10**16), ("P10_5", 10**32),
          ("C1E7", 10**7), ("C1E8", 10**8)]

def table():
    out = {}
    for name, v in CONSTS:
        out[name] = encode(Fraction(v), prefer_int=False).b
    out["CHALF"] = encode(Fraction(1, 2), prefer_int=False).b
    return out

if __name__ == "__main__":
    t = table()
    lines = ["; GENERATED by tools/genconst.py -- do not edit by hand",
             "; SPDX-License-Identifier: Apache-2.0 OR GPL-2.0-only OR GPL-3.0-only OR MPL-2.0"]
    for name, _ in CONSTS + [("CHALF", 0)]:
        b = t[name]
        lines.append(f"{name}:  DEFB {', '.join('0x%02X' % x for x in b)}")
    open("src/p10const.asm", "w").write("\n".join(lines) + "\n")
    print("\n".join(lines[2:]))
