"""Coefficient and constant generator for the M3 circular functions
and the arctangent family.

Chebyshev near-minimax fits via mpmath.chebyfit, freshly computed (no
third-party tables), rounded to the 5-byte format by the oracle encoder.
Emits src/trigconst.asm and an importable table.

Reduction: n = floor(x*(2/pi) + 0.5); three-term Cody-Waite
  r = ((x - n*P1) - n*P2) - n*P3
with P1 = pi/2 truncated to 16 mantissa bits and P2 the next 16 bits, so
n*P1 and n*P2 are exact in the 32-bit mantissa for |n| <= 65535; only
the n*P3 product rounds. |r| <= pi/4 (+ rounding slack).

Kernels on w = r^2, w in [0, 0.62]:
  sin(r) = r * PS(w),  PS(w) = sin(sqrt(w))/sqrt(w)
  cos(r) = PC(w)
"""
import sys
sys.path.insert(0, __file__.rsplit("/", 1)[0])
from fractions import Fraction
from math import floor
import mpmath as mp
from oracle import encode, FP5

mp.mp.prec = 120

W_MAX = 0.62  # (pi/4)^2 = 0.61685, plus reduction slack


def frac_of(x) -> Fraction:
    t = mp.mpf(x)
    m, e = t._mpf_[1], t._mpf_[2]
    if t < 0:
        m = -m
    return Fraction(int(m), 1) * Fraction(2) ** int(e)


def fit(f, a, b, deg):
    poly, err = mp.chebyfit(f, [a, b], deg, error=True)
    return [frac_of(c) for c in poly], float(err)


def main():
    half_pi = frac_of(mp.pi / 2)
    # P1: top 16 significant bits (value in [1,2): resolution 2^-15)
    p1 = Fraction(floor(half_pi * 2**15), 2**15)
    d1 = half_pi - p1                       # in [0, 2^-15)
    # P2: next 16 bits (down to 2^-31)
    p2 = Fraction(floor(d1 * 2**31), 2**31)
    p3 = half_pi - p1 - p2                  # ~2^-32; encoded rounded
    two_over_pi = frac_of(2 / mp.pi)

    def PS(w):
        if w == 0:
            return mp.mpf(1)
        z = mp.sqrt(w)
        return mp.sin(z) / z

    def PC(w):
        return mp.cos(mp.sqrt(w))

    # 5/6 coefficients give fit errors of ~0.02 and ~0.0003 ulp of a
    # unit-scale result -- one more coefficient each buys nothing the
    # 32-bit mantissa can keep, one fewer costs 13 ulp (PS at 4).
    ps, pserr = fit(PS, 0, W_MAX, 5)        # degree 4 in w
    pc, pcerr = fit(PC, 0, W_MAX, 6)        # degree 5 in w

    # atan kernel: atn(z) = z*PA(z^2), |z| <= tan(pi/8) after octant
    # reduction. 8 coefficients: fit error 8.1e-13 (~0.01 ulp); 7 gives
    # 2.3e-11 which is a visible 0.4 ulp of the smallest kernel scale.
    tan8 = frac_of(mp.tan(mp.pi / 8))
    wa_max = float(tan8 * tan8) * 1.01

    def PA(w):
        if w == 0:
            return mp.mpf(1)
        z = mp.sqrt(w)
        return mp.atan(z) / z

    pa, paerr = fit(PA, 0, wa_max, 8)       # degree 7 in w

    named = [("C2OPI", encode(two_over_pi, prefer_int=False)),
             ("CP1", encode(p1, prefer_int=False)),
             ("CP2", encode(p2, prefer_int=False)),
             ("CP3", encode(p3, prefer_int=False)),
             ("CT8", encode(tan8, prefer_int=False)),
             ("CPI4", encode(frac_of(mp.pi / 4), prefer_int=False)),
             ("CPI2", encode(frac_of(mp.pi / 2), prefer_int=False))]
    pstab = [encode(c, prefer_int=False) for c in ps]
    pctab = [encode(c, prefer_int=False) for c in pc]
    patab = [encode(c, prefer_int=False) for c in pa]

    lines = ["; GENERATED by tools/gentrig.py -- do not edit by hand",
             "; SPDX-License-Identifier: Apache-2.0 OR GPL-2.0-only OR GPL-3.0-only OR MPL-2.0",
             f"; sin kernel Chebyshev fit error: {pserr:.3e}",
             f"; cos kernel Chebyshev fit error: {pcerr:.3e}",
             f"; atan kernel Chebyshev fit error: {paerr:.3e}"]
    for name, v in named:
        lines.append(f"{name}:  DEFB {', '.join('0x%02X' % x for x in v.b)}")
    lines.append(f"SINPOLY_N: DEFB {len(pstab)}")
    lines.append("SINPOLY:")
    for i, v in enumerate(pstab):
        lines.append(f"        DEFB {', '.join('0x%02X' % x for x in v.b)} ; w^{len(pstab)-1-i}")
    lines.append(f"COSPOLY_N: DEFB {len(pctab)}")
    lines.append("COSPOLY:")
    for i, v in enumerate(pctab):
        lines.append(f"        DEFB {', '.join('0x%02X' % x for x in v.b)} ; w^{len(pctab)-1-i}")
    lines.append(f"ATNPOLY_N: DEFB {len(patab)}")
    lines.append("ATNPOLY:")
    for i, v in enumerate(patab):
        lines.append(f"        DEFB {', '.join('0x%02X' % x for x in v.b)} ; w^{len(patab)-1-i}")
    open("src/trigconst.asm", "w").write("\n".join(lines) + "\n")
    print("\n".join(lines[:4]))
    print(f"PS: {len(pstab)}, PC: {len(pctab)}, PA: {len(patab)} coefficients")
    # sanity: exactness preconditions for the Cody-Waite products
    assert encode(p1, prefer_int=False).to_fraction() == p1
    assert encode(p2, prefer_int=False).to_fraction() == p2
    return {"PS": pstab, "PC": pctab, "PA": patab, "named": dict(named)}


_cache = None
def _cached():
    global _cache
    if _cache is None:
        import io, contextlib
        with contextlib.redirect_stdout(io.StringIO()):
            _cache = main()
    return _cache


if __name__ == "__main__":
    main()
